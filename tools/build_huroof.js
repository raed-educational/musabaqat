// Builds data/huroof.js: for each Arabic letter, questions whose answer starts with that letter
// (after removing diacritics, quotes and the definite article «ال»). Options are hidden in حروف,
// so questions that depend on their options ("أي مما يأتي…") are excluded.
// Usage: node tools/build_huroof.js   (prints per-letter counts)
const fs = require('fs'), path = require('path');
global.window = global;
const ROOT = path.resolve(__dirname, '..');
fs.readdirSync(path.join(ROOT, 'data/bank')).forEach(f => require(path.join(ROOT, 'data/bank', f)));
const { stageOf } = require(path.join(ROOT, 'js/stages.js'));
const LETTERS = 'ابتثجحخدذرزسشصضطظعغفقكلمنهوي'.split('');
const BAD = /مما يأتي|مما يلي|التالي|الآتي|الآتية|التالية|ليس من|ليست من|أيّ هذه|أي هذه|ما عدا|باستثناء|ما سبق|الخيارات|صواب|خطأ|هؤلاء|مَن مِن|من من /;
const strip = s => String(s || '').replace(/[\u0610-\u061A\u064B-\u065F\u0670\u06D6-\u06ED\u0640]/g, '');
function firstLetter(a) {
  let s = strip(a).replace(/[﴿﴾«»"'()\[\]\-–—.:،,؛!؟?*]/g, ' ').trim();
  s = s.replace(/^ال(?=[\u0621-\u064A]{2})/, '');
  const c = s[0]; if (!c) return null;
  return c.replace(/[أإآٱء]/, 'ا').replace('ى', 'ي').replace('ة', 'ه').replace('ؤ', 'و').replace('ئ', 'ي');
}
function ans(q) { if (q.type === 'mcq' || q.type === 'who') return q.options[q.answer]; if (q.type === 'fill') return q.answer; return null; }
const all = [].concat(...Object.values(window.QUIZ_BANK));
const seen = {};
const by = {}; LETTERS.forEach(l => by[l] = []);
all.forEach(q => {
  const a = ans(q); if (!a || BAD.test(q.question)) return;
  const A = strip(a).trim();
  if (A.split(/\s+/).length > 4 || A.length > 40 || /^[0-9٠-٩]/.test(A)) return;
  if (/____/.test(q.question) && q.type !== 'fill') return;
  if (/(^|\s)[\u0621-\u064A](\s|$)/.test(A)) return; // root letters like «ظ ل م»
  const L = firstLetter(A); if (!by[L]) return;
  const key = L + '|' + A; seen[key] = (seen[key] || 0) + 1; if (seen[key] > 3) return; // avoid «ثقة/ضعيف» floods
  by[L].push(q);
});
const CAP = 260; // per letter, balanced across categories and difficulties
const out = {}; const report = [];
LETTERS.forEach(L => {
  const list = by[L];
  const groups = {}; list.forEach(q => { const k = q.category + '|' + q.difficulty; (groups[k] = groups[k] || []).push(q); });
  Object.values(groups).forEach(g => g.sort((a, b) => (b.verified ? 1 : 0) - (a.verified ? 1 : 0) || a.id.localeCompare(b.id)));
  const keys = Object.keys(groups).sort(); const pick = []; let i = 0;
  while (pick.length < Math.min(CAP, list.length)) { const g = groups[keys[i++ % keys.length]]; if (g.length) pick.push(g.shift()); }
  out[L] = pick.map(q => [q.id, q.category, +q.difficulty || 2, stageOf(q), q.question, strip(ans(q)).trim(), q.type === 'who' ? q.clues : 0, q.source || '', q.subcategory || '']);
  report.push({ L, total: list.length, kept: out[L].length, cats: new Set(list.map(q => q.category)).size });
});
fs.writeFileSync(path.join(ROOT, 'data/huroof.js'), '/* generated by tools/build_huroof.js */\nwindow.HUROOF_Q=' + JSON.stringify(out) + ';\nwindow.HUROOF_TOTALS=' + JSON.stringify(Object.fromEntries(report.map(r => [r.L, r.total]))) + ';\n');
report.forEach(r => console.log(r.L, 'candidates', r.total, 'kept', r.kept, 'cats', r.cats));
console.log('size', fs.statSync(path.join(ROOT, 'data/huroof.js')).size);
